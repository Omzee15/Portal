// The test-only reset: a finished daily can be played again, other data survives, and production builds don't expose it.
import { chromium } from "playwright";
const BASE = process.env.BASE ?? "http://127.0.0.1:3100";
const PROD = process.env.PROD_BASE ?? "http://127.0.0.1:3102";
let fail = 0;
const check = (n, c, x = "") => { console.log(c ? "PASS" : "FAIL", n, x); if (!c) fail++; };
const A = await (await fetch(`${BASE}/api/e2e-answers`)).json();
const b = await chromium.launch();
const ctx = await b.newContext();
const p = await ctx.newPage();
await p.goto(`${BASE}/play/emoji-decode`, { waitUntil: "networkidle" });
await p.fill('input[aria-label="Your answer"]', A.emoji.title);
await p.click("text=Go");
await p.waitForTimeout(800);
const keys = () => p.evaluate(() => Object.keys(localStorage));
check("a finished game is saved", (await keys()).some((k) => k.startsWith("portal:emoji:")));
check("the attempt cookie is set", (await ctx.cookies()).some((c) => c.name === "lb_emoji"));
await p.evaluate(() => { localStorage.setItem("portal:name", "Asha"); });
await p.goto(`${BASE}/api/e2e-reset`);
await p.waitForURL(`${BASE}/`);
await p.waitForTimeout(400);
check("today's save is gone", !(await keys()).some((k) => k.startsWith("portal:emoji:")));
check("the attempt cookie is gone", !(await ctx.cookies()).some((c) => c.name === "lb_emoji"));
check("the player's name is kept", (await p.evaluate(() => localStorage.getItem("portal:name"))) === "Asha");
await p.goto(`${BASE}/play/emoji-decode`, { waitUntil: "networkidle" });
await p.fill('input[aria-label="Your answer"]', A.emoji.title);
await p.click("text=Go");
await p.waitForTimeout(800);
check("the game can be solved again", /Solved|cracked|Share/i.test(await p.textContent("body")));
// Needs a production server (`next build && next start -p 3102`, without PORTAL_E2E) on PROD_BASE.
const prod = await fetch(`${PROD}/api/e2e-reset`).catch(() => null);
if (prod) check("hidden on a normal server", prod.status === 404);
else console.log(`SKIP hidden on a normal server (nothing running on ${PROD})`);
await b.close();
console.log(fail ? `${fail} failed` : "all passed");
process.exit(fail ? 1 : 0);
